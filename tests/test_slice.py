"""PCAP slicing by host, frame and flow (#256).

The slicer writes a subset capture. These tests read the OUTPUT capture back with scapy, so they
run without tshark and assert on real frames rather than on a summary object.

Frame numbers are 1-based and match the order frames appear in the input capture.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from scapy.all import IP, TCP, UDP, rdpcap

from conftest import fixture
from pcap_doctor.slice import slice_capture


def flow_keys(path: Path) -> list[tuple[str, int, str, int]]:
    """Every frame as a (src, sport, dst, dport) tuple; port 0 for a frame with no ports."""
    keys = []
    for frame in rdpcap(str(path)):
        if IP not in frame:
            continue
        ip = frame[IP]
        l4 = frame.getlayer(TCP) or frame.getlayer(UDP)
        keys.append(
            (ip.src, int(l4.sport) if l4 is not None else 0, ip.dst, int(l4.dport) if l4 is not None else 0)
        )
    return keys


# The fixture's seven frames, verified with scapy against the generated bytes.
ALL_FRAMES = [
    ("10.96.0.1", 40000, "10.96.0.2", 80),
    ("10.96.0.2", 80, "10.96.0.1", 40000),
    ("10.96.0.1", 40000, "10.96.0.2", 80),
    ("10.96.0.1", 40001, "10.96.0.3", 80),
    ("10.96.0.3", 80, "10.96.0.1", 40001),
    ("10.96.0.1", 40001, "10.96.0.3", 80),
    ("10.96.0.4", 53000, "10.96.0.9", 53),
]


def test_fixture_has_the_seven_frames_the_expectations_are_built_on(tmp_path: Path) -> None:
    copy = tmp_path / "copy.pcap"
    copy.write_bytes(fixture("slice_hosts.pcap").read_bytes())
    assert flow_keys(copy) == ALL_FRAMES


def test_slice_by_frame_numbers_keeps_only_those_frames(tmp_path: Path) -> None:
    out = tmp_path / "s.pcap"
    result = slice_capture(fixture("slice_hosts.pcap"), out, frame=[1, 2, 3])
    assert flow_keys(out) == ALL_FRAMES[0:3]
    assert result.frames == [1, 2, 3]


def test_slice_by_frame_numbers_preserves_the_requested_order(tmp_path: Path) -> None:
    out = tmp_path / "s.pcap"
    result = slice_capture(fixture("slice_hosts.pcap"), out, frame=[5, 2])
    assert flow_keys(out) == [ALL_FRAMES[4], ALL_FRAMES[1]]
    assert result.frames == [5, 2]


def test_slice_by_host_keeps_every_frame_touching_it_in_both_directions(tmp_path: Path) -> None:
    out = tmp_path / "s.pcap"
    result = slice_capture(fixture("slice_hosts.pcap"), out, host="10.96.0.2")
    assert flow_keys(out) == ALL_FRAMES[0:3]
    assert result.frames == [1, 2, 3]


def test_slice_by_host_matches_the_destination_of_the_single_dns_frame(tmp_path: Path) -> None:
    out = tmp_path / "s.pcap"
    result = slice_capture(fixture("slice_hosts.pcap"), out, host="10.96.0.9")
    assert flow_keys(out) == [ALL_FRAMES[6]]
    assert result.frames == [7]


def test_slice_by_host_covers_both_directions_of_every_conversation_it_touches(tmp_path: Path) -> None:
    out = tmp_path / "s.pcap"
    result = slice_capture(fixture("slice_hosts.pcap"), out, host="10.96.0.1")
    assert result.frames == [1, 2, 3, 4, 5, 6]
    assert flow_keys(out) == ALL_FRAMES[0:6]


def test_slice_by_flow_keeps_exactly_that_conversation(tmp_path: Path) -> None:
    out = tmp_path / "s.pcap"
    result = slice_capture(fixture("slice_hosts.pcap"), out, flow="10.96.0.1:40001-10.96.0.3:80")
    assert result.frames == [4, 5, 6]
    assert flow_keys(out) == ALL_FRAMES[3:6]


def test_the_two_flows_are_told_apart_by_the_client_port_alone(tmp_path: Path) -> None:
    first = tmp_path / "a.pcap"
    second = tmp_path / "b.pcap"
    assert slice_capture(fixture("slice_hosts.pcap"), first, flow="10.96.0.1:40000-10.96.0.2:80").frames == [
        1,
        2,
        3,
    ]
    assert slice_capture(fixture("slice_hosts.pcap"), second, flow="10.96.0.1:40001-10.96.0.3:80").frames == [
        4,
        5,
        6,
    ]


def test_slice_reports_the_input_size_and_the_output_path(tmp_path: Path) -> None:
    out = tmp_path / "s.pcap"
    result = slice_capture(fixture("slice_hosts.pcap"), out, host="10.96.0.2")
    assert result.total_frames == 7
    assert result.path == out


def test_a_selector_that_matches_nothing_writes_an_empty_capture(tmp_path: Path) -> None:
    out = tmp_path / "s.pcap"
    result = slice_capture(fixture("slice_hosts.pcap"), out, host="10.99.99.99")
    assert result.frames == []
    assert out.exists()
    assert len(rdpcap(str(out))) == 0


def test_two_selectors_at_once_is_rejected(tmp_path: Path) -> None:
    with pytest.raises(ValueError):
        slice_capture(fixture("slice_hosts.pcap"), tmp_path / "s.pcap", host="10.96.0.2", frame=[1])


def test_no_selector_at_all_is_rejected(tmp_path: Path) -> None:
    with pytest.raises(ValueError):
        slice_capture(fixture("slice_hosts.pcap"), tmp_path / "s.pcap")


def test_a_frame_number_past_the_end_of_the_capture_is_rejected(tmp_path: Path) -> None:
    with pytest.raises(ValueError):
        slice_capture(fixture("slice_hosts.pcap"), tmp_path / "s.pcap", frame=[1, 99])


def test_a_flow_that_is_not_in_the_capture_is_rejected(tmp_path: Path) -> None:
    with pytest.raises(ValueError):
        slice_capture(fixture("slice_hosts.pcap"), tmp_path / "s.pcap", flow="10.96.0.1:49999-10.96.0.2:80")


def test_the_output_is_a_readable_capture_of_the_same_link_type(tmp_path: Path) -> None:
    out = tmp_path / "s.pcap"
    slice_capture(fixture("slice_hosts.pcap"), out, frame=[2])
    written = rdpcap(str(out))
    assert len(written) == 1
    assert bytes(written[0]) == bytes(rdpcap(str(fixture("slice_hosts.pcap")))[1])
