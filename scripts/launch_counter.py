"""tshark launch counter used by ``bench_large.py`` and ``tests/test_launch_budget.py``.

The analyzer counts its work in *tshark launches* (one tshark process per pass),
not in wall time. There is no repeatable way to measure that from inside the same
process, so these helpers drop a tiny ``tshark`` wrapper executable ahead of the
real one on ``PATH`` and have every launch append a line to a log file, which is
then read back and classified.

A launch is recorded as its full argument list (``"$*"``). The cheap classifier
below excludes the tshark *lookups* (``-v`` version, ``-G fields``,
``-G protocols``, ``-G defaultprefs``) -- those are capability discovery, not
analysis passes -- matching the regression guard's "excluding ``tshark -G``
lookups" wording. Everything else (``tshark -r pcap ...``) is a pass launch.
"""

from __future__ import annotations

import os
import shutil
import stat
import sys
import tempfile
from pathlib import Path

#: Argument tokens that mark a non-pass lookup (capability discovery), not an
#: analysis pass. ``-G`` lookups are explicitly excluded by the launch budget;
#: ``-v`` is the version probe that the wrapper does not count either.
_LOOKUP_FLAGS = ("-G", "-v")

_WRAPPER_TEMPLATE = """\
#!/bin/sh
# Generated by scripts/launch_counter.py -- records each tshark launch then execs the real binary.
printf '%s\\n' "$*" >> "{log}"
exec "{real}" "$@"
"""


def real_tshark() -> str:
    """Resolve the real ``tshark`` binary without a wrapper shadowing it."""
    return shutil.which("tshark") or ""


def make_wrapper(log_path: Path) -> Path:
    """Create a temp bin dir holding a ``tshark`` wrapper that logs launches.

    Returns the bin dir so the caller can prepend it to ``PATH``. The returned
    directory and the log file are cleaned up with the temp file lifecycle;
    callers own the returned ``bin_dir``.
    """
    bin_dir = Path(tempfile.mkdtemp(prefix="tshark-wrap-"))
    log_path.parent.mkdir(parents=True, exist_ok=True)
    log_path.write_text("", encoding="utf-8")
    real = real_tshark()
    if not real:
        raise FileNotFoundError("tshark not found on PATH; cannot build a wrapper")
    wrapper = bin_dir / "tshark"
    wrapper.write_text(_WRAPPER_TEMPLATE.format(log=log_path, real=real), encoding="utf-8")
    wrapper.chmod(stat.S_IRWXU | stat.S_IRGRP | stat.S_IXGRP | stat.S_IROTH | stat.S_IXOTH)
    return bin_dir


def classify(line: str) -> str:
    """Return ``"lookup"`` for capability probes, ``"pass"`` for analysis launches."""
    return "lookup" if any(flag in line for flag in _LOOKUP_FLAGS) else "pass"


def count_launches(log_path: Path) -> int:
    """Count pass launches (lookups excluded).

    Missing log file means nothing launched.
    """
    if not log_path.exists():
        return 0
    text = log_path.read_text(encoding="utf-8", errors="replace")
    return sum(1 for line in text.splitlines() if line and classify(line) == "pass")


def with_wrapped_path(bin_dir: Path) -> dict[str, str]:
    """Return an env dict with ``bin_dir`` first on ``PATH``."""
    env = dict(os.environ)
    env["PATH"] = f"{bin_dir}{os.pathsep}{env.get('PATH', os.defpath)}"
    return env


def _example() -> None:
    """Tiny CLI so scripts can reuse the same counter without duplicating logic."""
    import argparse

    parser = argparse.ArgumentParser(description="Count tshark pass launches in a log.")
    parser.add_argument("log", type=Path)
    args = parser.parse_args()
    print(count_launches(args.log))


if __name__ == "__main__":
    _example()
    sys.exit(0)
